# frozen_string_literal: true

# Builds tags.rb, attr.rb and entities.rb from the C# sources of z3l.FastHtmlParser, so that the Ruby port uses
# exactly the same tag list, attribute names and HTML5 entity table, and writes the one-call shortcuts
# (find_by_name_class, is_name_class?, parent_by_name, ...) into html_document.rb and html_node.rb between the
# "# <shortcuts ...>" markers.
#
#   ruby tools/gen.rb ../z3l.FastHtmlParser/src/z3l.FastHtmlParser

OUT = File.expand_path("../lib/fasthtmlparser", __dir__)

def read(path)
  File.binread(path).force_encoding(Encoding::UTF_8).gsub("\r\n", "\n")
end

def write(name, text)
  File.binwrite(File.join(OUT, name), text)
end

def header(from, binary: false)
  enc = binary ? "# encoding: ascii-8bit\n" : ""
  "#{enc}# frozen_string_literal: true\n\n# Code generated by tools/gen.rb from #{from}; DO NOT EDIT.\n\n"
end

# The member names of a C# enum without explicit values, in order.
def enum_members(path, name)
  text = read(path)
  body = text[text.index("public enum #{name}")..]
  body = body[(body.index("{") + 1)...body.rindex("}")]
  body.split("\n").filter_map do |line|
    line = line.sub(%r{//.*}, "").strip.chomp(",").strip
    line unless line.empty?
  end
end

# PascalCase to UPPER_SNAKE: DataSrc -> DATA_SRC, XmlDeclaration -> XML_DECLARATION, H1 -> H1.
def constant_name(pascal)
  out = +""
  pascal.each_char.with_index do |c, i|
    out << "_" if i.positive? && c.match?(/[A-Z]/) && pascal[i - 1].match?(/[a-z0-9]/)
    out << c.upcase
  end
  out
end

# A Ruby string literal of the bytes, every non-ASCII byte as \xNN (the file is ascii-8bit).
def binary_literal(bytes)
  body = bytes.bytes.map do |c|
    case c
    when 0x22 then '\\"'
    when 0x5c then "\\\\"
    when 0x23 then "\\#"
    when 0x0a then "\\n"
    when 0x09 then "\\t"
    when 0x20..0x7e then c.chr
    else format("\\x%02X", c)
    end
  end
  "\"#{body.join}\""
end

# ----- tags -----

def tags(src)
  special = { "Comment" => "!--", "Doctype" => "!doctype", "XmlDeclaration" => "?xml" }
  members = enum_members(File.join(src, "HtmlTag.cs"), "HtmlTag")
  names = {}
  consts = +""
  members.each do |m|
    name = special[m] || m.downcase
    raise "duplicate tag #{name}" if names.key?(name)

    names[name] = names.size
    sym = name.match?(/\A[a-z][a-z0-9_]*\z/) ? ":#{name}" : ":\"#{name}\""
    consts << "    #{constant_name(m)} = #{sym}\n"
  end
  b = header("HtmlTag.cs")
  b << "module FastHtmlParser\n"
  b << "  # Known tag names: HTML (incl. obsolete), SVG, MathML and common XML (RSS, Atom, sitemap), as symbols of the\n"
  b << "  # lower-case name (Tag::DIV is :div; :\"!--\" for comments, :\"!doctype\", :\"?xml\"). Any other name works as a\n"
  b << "  # Symbol or String in the methods that take a tag name.\n"
  b << "  module Tag\n#{consts}  end\n\n"
  b << "  # @api private The tag names by ordinal (the order of the C# enum) and the ordinals by name.\n"
  b << "  module TagNames\n"
  b << "    NAMES = [\n"
  names.each_key { |n| b << "      \"#{n}\",\n" }
  b << "    ].freeze\n\n    KEYS = {\n"
  names.each { |n, k| b << "      \"#{n}\" => #{k},\n" }
  b << "    }.freeze\n  end\nend\n"
  write("tags.rb", b)
  members.size
end

# ----- attributes -----

def attributes(src)
  special = read(File.join(src, "Core/HtmlNames.cs")).scan(/HtmlAttribute\.(\w+) => "([^"]+)"/).to_h
  members = enum_members(File.join(src, "HtmlAttribute.cs"), "HtmlAttribute")
  seen = {}
  b = header("HtmlAttribute.cs and HtmlNames.cs")
  b << "module FastHtmlParser\n"
  b << "  # Common HTML / SVG / XML attribute names, for HtmlNode#attr, Query#attr and the shortcuts. Any other name\n"
  b << "  # works as a plain String or Symbol.\n"
  b << "  module Attr\n"
  members.each do |m|
    name = special[m] || m.downcase
    c = constant_name(m)
    raise "duplicate attribute #{name} / #{c}" if seen.key?(name) || seen.key?(c)

    seen[name] = seen[c] = true
    b << "    #{c} = \"#{name}\"\n"
  end
  b << "  end\nend\n"
  write("attr.rb", b)
  members.size
end

# ----- entities -----

# The concatenated string literals of `name = "..." + "...";`, escapes left as written.
def constant_text(text, name)
  start = text.index("#{name} =")
  stop = text.index(";", start)
  text[start...stop].scan(/"((?:[^"\\]|\\.)*)"/).map(&:first).join
end

# C# escapes (\uXXXX, \0) into a list of UTF-16 units.
def units(s)
  out = []
  i = 0
  while i < s.length
    c = s[i]
    if c == "\\" && i + 1 < s.length
      e = s[i + 1]
      if e == "u"
        out << s[i + 2, 4].to_i(16)
        i += 6
        next
      elsif e == "0"
        out << 0
        i += 2
        next
      end
      raise "unexpected escape \\#{e}"
    end
    out << c.ord
    i += 1
  end
  out
end

def utf8(cp)
  [cp].pack("U").b
end

def entities(src)
  table = read(File.join(src, "Core/HtmlEntities.Table.cs"))
  names = constant_text(table, "private const string Names").strip.split(/\s+/)
  us = units(constant_text(table, "private const string Values"))
  raise "#{names.size} names, #{us.size} value units" unless us.size == 2 * names.size

  max_name = 0
  max_legacy = 0
  map = +""
  legacy = +""
  names.each_with_index do |n, i|
    is_legacy = n.start_with?("+")
    name = is_legacy ? n[1..] : n
    max_name = [max_name, name.size].max
    a = us[2 * i]
    z = us[2 * i + 1]
    value = if z.zero?
              utf8(a)
            elsif a.between?(0xd800, 0xdbff)
              utf8(0x10000 + ((a - 0xd800) << 10) + (z - 0xdc00))
            else
              utf8(a) + utf8(z)
            end
    map << "      \"#{name}\" => #{binary_literal(value)},\n"
    if is_legacy
      max_legacy = [max_legacy, name.size].max
      legacy << "      \"#{name}\" => true,\n"
    end
  end
  b = header("HtmlEntities.Table.cs", binary: true)
  b << "module FastHtmlParser\n"
  b << "  # @api private The HTML5 named character references; the values are UTF-8 bytes.\n"
  b << "  module Entities\n"
  b << "    MAX_NAME = #{max_name}\n    MAX_LEGACY_NAME = #{max_legacy}\n\n"
  b << "    # The names without \"&\" and \";\" and their values.\n"
  b << "    MAP = {\n#{map}    }.freeze\n\n"
  b << "    # The legacy names, which are also recognized without \";\".\n"
  b << "    LEGACY = {\n#{legacy}    }.freeze\n  end\nend\n"
  write("entities.rb", b)
  names.size
end

