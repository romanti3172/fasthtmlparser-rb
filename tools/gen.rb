def params(p)
  p.sub(/\AN\b/, "name")
end

def emit_method(doc, name, params, body)
  args = params.empty? ? "" : "(#{params(params)})"
  "    # #{doc}\n    def #{name}#{args}\n#{body}    end\n\n"
end

def block(scope)
  b = +"    # Generated by tools/gen.rb; do not edit by hand.\n\n"
  FINDS.each do |name, params, query, guard, doc|
    body = guard.empty? ? +"" : +"      return nil if #{guard}\n\n"
    body << "      find(#{query})\n"
    b << emit_method("Returns #{doc} #{scope}, or nil.", name, params, body)
  end
  FIND_ALLS.each do |name, params, query, doc|
    b << emit_method("Returns #{doc} #{scope}.", name, params, "      find_all(#{query})\n")
  end
  b
end

def node_only
  b = +""
  ISS.each { |name, params, query, doc| b << emit_method("Whether #{doc}.", name, params, "      is?(#{query})\n") }
  NAVS.each { |name, params, call, doc| b << emit_method("Returns #{doc}.", name, params, "      #{call}\n") }
  ATTRIBUTES.each do |name, constant, attribute|
    b << emit_method("The decoded value of the #{attribute} attribute; \"\" when it is missing.", name, "",
                "      attr(Attr::#{constant})\n")
  end
  b
end

def replace_block(file, marker, content)
  path = File.join(OUT, file)
  text = read(path)
  open = "    # <shortcuts #{marker}>\n"
  close = "    # </shortcuts #{marker}>"
  a = text.index(open)
  z = text.index(close)
  raise "no shortcut markers in #{file}" if a.nil? || z.nil? || z < a

  body = content.end_with?("\n\n") ? content[0...-1] : content
  File.binwrite(path, text[0, a + open.size] + body + text[z..])
end

def main(argv)
  if argv.size != 1
    warn "usage: ruby tools/gen.rb <path to src/z3l.FastHtmlParser>"
    exit 2
  end
  src = argv[0]
  t = tags(src)
  a = attributes(src)
  e = entities(src)
  replace_block("html_document.rb", "document", block("in the document"))
  replace_block("html_node.rb", "node", block("inside the tag") + node_only)
  puts "#{t} tags, #{a} attributes, #{e} entities, shortcuts written"
end

main(ARGV)
